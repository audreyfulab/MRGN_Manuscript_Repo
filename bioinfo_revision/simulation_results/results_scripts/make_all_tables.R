cell <- function(method, arm, size, level, pred.levels) {
    matrix.from.long(pooled[pooled$method == method & pooled$arm == arm &
                                pooled$level == level & pooled$sample_size == size, ,
                            drop = FALSE],
                     pred.levels)
}

for (arm in MRGN.ARMS) {
    lines <- c(lines, paste("###", sprintf("MRGN -- %s arm", arm)), "",
               ARM.BLURB[[arm]], "")
    for (size in SAMPLE.SIZES) {
        m <- cell("mrgn", arm, size, "model", MRGN.LEVELS)
        correct <- sum(diag(m[, TRUTH.LEVELS, drop = FALSE]))
        lines <- c(lines,
                   md.scored.table(scored.table(m, MRGN.CORRECT), sprintf("n = %d", size),
                                   sprintf("Accuracy: **%.1f%%** (%d of %d).",
                                           100 * correct / sum(m), correct, sum(m))))
    }
}

# ---- MRPC, scored the same way MRGN is ----
# Only the arms that actually produced results appear; an arm switched off in mrpc.arms is
# absent from the long counts, and printing an empty table for it would read as a result.
mrpc.arms.present <- intersect(MRPC.ARMS, unique(pooled$arm[pooled$method == "mrpc"]))

lines <- c(lines,
    "## MRPC",
    "",
    paste("MRPC names a trio topology, so it is scored on the same six-way call as MRGN",
          "and against the same eight adjacency matrices. Read the arms against MRGN's:",
          "same trios, same confounder sets, same right answers."),
    "",
    paste("**`Failed` is a real column here and it is a result, not a gap in the data.**",
          "Each MRPC fit is capped at `mrpc.timeout` seconds and returns no model when it",
          "expires. At the previous 120 s cap that was 182 of 300 trios at n = 670 and 224",
          "of 300 at n = 1000 in the CS-q arm alone; the cap is now 180 s. Timed-out trios",
          "count against accuracy, exactly as MRGN's `Other` and MR-GGI's",
          "`Weak instrument` do -- a fit that never returned is a model that was not",
          "identified. MRPC's accuracy *on the trios it finishes* is not its accuracy on",
          "this design, and the two should never be quoted interchangeably."),
    "")

for (arm in mrpc.arms.present) {
    lines <- c(lines, sprintf("### MRPC -- %s arm", arm), "",
               if (arm %in% names(ARM.BLURB)) ARM.BLURB[[arm]] else "", "")
    for (size in SAMPLE.SIZES) {
        m <- cell("mrpc", arm, size, "model", MRPC.LEVELS)
        if (sum(m) == 0) next
        correct <- sum(diag(m[, TRUTH.LEVELS, drop = FALSE]))
        failed <- if ("Failed" %in% colnames(m)) sum(m[, "Failed"]) else 0
        lines <- c(lines,
                   md.scored.table(scored.table(m, MRGN.CORRECT), sprintf("n = %d", size),
                                   sprintf(paste("Accuracy: **%.1f%%** (%d of %d).",
                                                 "Timed out: %d (%.1f%%)."),
                                           100 * correct / sum(m), correct, sum(m),
                                           failed, 100 * failed / sum(m))))
    }
}

lines <- c(lines,
    "## GMAC",
    "",
    paste("GMAC is scored on the **T1-T2 edge**, not on the trio topology. Its statistic",
          "is the Wald test on the mediator coefficient in",
          "`outcome ~ mediator + treatment + confounders`, and that regression is",
          "symmetric in T1 and T2 -- under `V1 -> T1 -> T2` the reverse coefficient is",
          "nonzero too, so the trans test fires whenever the cis one does. GMAC has no",
          "mechanism for orienting the edge: across all 1,500 trios `Cis Mediated` and",
          "`Trans Mediated` were picked 2 and 3 times."),
    "",
    paste("So the three edge-present calls (`Cis Mediated`, `Trans Mediated`,",
          "`Undirected`) are pooled and the table asks what GMAC can answer. `M0` and",
          "`M3` have no T1-T2 edge; `M1`, `M2` and `M4` do. This is the framing the",
          "manuscript already used --",
          "`Manuscript/other/tablescraps/MRGN.GMAC.class.inference.50conf` reports GMAC",
          "the same way. The four-way call is still in `inference_gmac.csv` if it is",
          "wanted."),
    "",
    paste("The tables are lopsided towards edge-present, and that is a failure of",
          "confounder selection rather than a property of the test: GMAC selects the trio's",
          "own common child about half the time at n = 670, and adjusting for a collider",
          "on T1 and T2 manufactures the edge. Given the true confounders instead, the",
          "same test calls `M0` and `M3` edge-absent."),
    "")

for (size in SAMPLE.SIZES) {
    m <- cell("gmac", "gmac", size, "edge", EDGE.LEVELS)
    es <- edge.scores(m)
    lines <- c(lines,
               md.scored.table(scored.table(m, EDGE.CORRECT), sprintf("n = %d", size),
                               sprintf("Edge accuracy: **%.1f%%** (%d of %d).",
                                       100 * es$accuracy, round(es$accuracy * sum(m)),
                                       sum(m))))
}

lines <- c(lines,
    "## MR-GGI",
    "",
    paste("MR-GGI is scored on the **T1-T2 edge** for a reason internal to the method",
          "rather than as a simplification of it. It is a Mendelian randomisation",
          "estimator: it fits T2 on T1 instrumented by V1 and tests whether that causal",
          "effect is nonzero. Nothing in that test looks at whether V1 also acts on T2",
          "directly, so `M0` and `M3` are the same trio to it, as are `M1` and `M4`. The",
          "two-row question is the one it answers, and the right answers are the same as",
          "GMAC's."),
    "",
    paste("MR-GGI gets a third row, and it is not the same row as MRGN's `Other`.",
          "`Weak instrument` means the first-stage F for `V1 -> T1` fell below",
          "`mrggi.min.F` (10, the conventional Staiger-Stock rule) and the edge was never",
          "tested. `mrggi.fields()` records those trios as `edge = \"none\"`, so reading",
          "the edge column alone would score an untested trio as a confident edge-absent",
          "call -- 570 of 1,500 trios, and 209 of 300 at n = 50. They are broken out",
          "instead, and count against accuracy: a trio whose edge was never called is a",
          "trio whose edge was not identified."),
    "",
    paste("That row is the finding rather than an inconvenience. The weak-instrument rate",
          "is a property of the **trio design**, not of the estimator -- there is one",
          "variant, and MR-GGI needs it to be a strong instrument for the cis gene. It",
          "falls from 70% at n = 50 to 19% at n = 1000, so MR-GGI's small-sample behaviour",
          "here is governed by instrument strength rather than by the test. Neither MRGN",
          "nor GMAC has an analogous gate."),
    "",
    paste("Only the cis -> trans direction is scored. The reverse estimate is in",
          "`inference_mrggi.csv` but is not an edge call: with a single instrument the",
          "test statistic reduces to the instrument -> outcome t-statistic and the",
          "exposure's first stage cancels out, so the reverse direction reports",
          "significance on trios where V1 does not instrument T2 at all. See",
          "`MRGGI_METHODS.md`."),
    "",
    paste("**Read the `M2` and `M3` columns before the accuracy figure.** Every other",
          "model recalls 0.65-0.78 at n = 1000; those two recall 0.02 and 0.03, and they",
          "account for most of the gap between MR-GGI's accuracy and the other methods'.",
          "Both are the method behaving as specified:"),
    "",
    paste("- `M3` (`V1 -> T1`, `V1 -> T2`, no T1-T2 edge) is called **edge-present** 48 of",
          "60 times. This is the exclusion-restriction violation MR cannot detect: V1 acts",
          "on T2 through a path that does not go through T1, and two-stage least squares",
          "attributes that association to a `T1 -> T2` effect. Horizontal pleiotropy is",
          "the known failure mode of single-instrument MR and `M3` is its textbook case,",
          "so this column measures it rather than exposing a defect in the tabulation."),
    paste("- `M2` (`V1 -> T1 <- T2`, edge present but oriented `T2 -> T1`) is called",
          "**edge-absent** 47 of 60 times. Here MR-GGI is arguably right and the scoring",
          "is what is coarse: it tests the cis -> trans effect, which under `M2` genuinely",
          "is zero. It is penalised because the table asks only whether an edge exists, in",
          "either direction."),
    "",
    paste("`M2` is scored the same way regardless, because the alternative is worse: the",
          "point of the two-row framing is that all three methods face identical rows,",
          "columns and right answers, and giving MR-GGI its own definition of correct",
          "would make its accuracy incomparable with the other two. GMAC's symmetric Wald",
          "test does find `M2`'s edge, and that difference between the methods is itself a",
          "result. Quote this caveat beside any MR-GGI accuracy figure."),
    "")

