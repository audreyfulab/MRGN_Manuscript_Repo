          round(edge.summary[, -(1:4)], 4)),
    summary.path, row.names = FALSE)
cat(sprintf("  wrote %s | %d rows\n", basename(summary.path), nrow(edge.summary)))

# one row per method-arm, one column per sample size, for each of the four rates worth
# comparing. Four small tables beat one 10-column table nobody can read across.
label.of <- function(method, arm) {
    switch(method, gmac = "GMAC", mrggi = "MR-GGI", sprintf("MRGN %s", arm))
}
rate.table <- function(column, title, blurb) {
    header <- c("method", sprintf("n = %d", SAMPLE.SIZES))
    rows <- vapply(seq_len(nrow(COMPARE)), function(i) {
        v <- edge.summary[edge.summary$method == COMPARE$method[i] &
                              edge.summary$arm == COMPARE$arm[i], column]
        paste("|", paste(c(label.of(COMPARE$method[i], COMPARE$arm[i]),
                           ifelse(is.na(v), "--", sprintf("%.3f", v))), collapse = " | "), "|")
    }, character(1))
    c(paste("####", title), "", blurb, "",
      paste("|", paste(header, collapse = " | "), "|"),
      paste("|", paste(rep("---", length(header)), collapse = " | "), "|"),
      rows, "")
}

