fmt.scorecard <- function(sc) {
    data.frame(
        Selection      = sc$selection,
        Group          = sc$group,
        Trios          = sc$trios,
        `Pool width`   = num(sc$pool.width),
        `Median true`  = sc$med.true,
        `Median selected` = sc$med.selected,
        Precision      = pct(sc$mean.prec),
        Recall         = pct(sc$mean.recall),
        `Selected nothing` = sc$n.undef.prec,
        `Median FP`    = sc$med.fp,
        `FP from other trios` = sc$med.fp.other,
        check.names = FALSE, stringsAsFactors = FALSE)
}

# ---- the 2x2 selection tables, both views -------------------------------------------
sel.conf.block <- function(view) {
    lines <- character()
    for (p in names(SELECTION.METHODS)) {
        mats <- selection.confusion(per.trio, p, view)
        for (k in names(mats)) {
            m  <- mats[[k]]
            tp <- m[1, 1]; fn <- m[1, 2]; fp <- m[2, 1]; tn <- m[2, 2]
            tbl <- data.frame(
                ` `                = rownames(m),
                Selected           = c(num(tp), num(fp)),
                `Not selected`     = c(num(fn), num(tn)),
                check.names = FALSE, stringsAsFactors = FALSE)
            lines <- c(lines,
                sprintf("#### %s -- %s", unname(SELECTION.METHODS[p]),
                        view.label(view, k)),
                "",
                md.table(tbl, align.right = FALSE),
                "",
                sprintf(paste("Precision %s | recall %s | specificity %s |",
                              "%s candidate covariate-trio pairs."),
                        pct(tp / (tp + fp)), pct(tp / (tp + fn)),
                        pct(tn / (tn + fp)), num(sum(m))),
                "")
        }
    }
    lines
}

