pct <- function(x, d = 1) ifelse(is.na(x), "--", sprintf(paste0("%.", d, "f%%"), 100 * x))
num <- function(x) formatC(x, format = "d", big.mark = ",")

# Renders a data.frame as a GitHub table. Hand-rolled for the same reason
# md.scored.table() is: nothing else in this stage pulls in knitr.
md.table <- function(df, align.right = TRUE) {
    cells <- as.data.frame(lapply(df, function(col)
        trimws(if (is.numeric(col)) formatC(col, format = "fg", digits = 4)
               else as.character(col))),
        stringsAsFactors = FALSE)
    c(paste("|", paste(names(df), collapse = " | "), "|"),
      paste("|", paste(rep(if (align.right) "---:" else "---", ncol(df)), collapse = " | "), "|"),
      apply(cells, 1, function(r) paste("|", paste(r, collapse = " | "), "|")))
}

sel      <- load.selection()
